import { defineField, defineType } from 'sanity'

export const article = defineType({
  name: 'article',
  title: 'Article',
  type: 'document',
  groups: [
    { name: 'content', title: 'Content', default: true },
    { name: 'meta', title: 'Meta & reviewers' },
    { name: 'seo', title: 'SEO' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      group: 'content',
      validation: (r) => r.required().max(90),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'content',
      options: { source: 'title' },
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'articleType',
      title: 'Article type',
      type: 'string',
      group: 'content',
      options: {
        list: [
          { title: 'Explainer', value: 'explainer' },
          { title: 'Myth-buster', value: 'mythBuster' },
          { title: 'Doctor guide', value: 'doctorGuide' },
          { title: 'Personal insight', value: 'personalInsight' },
          { title: 'News', value: 'news' },
        ],
      },
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'reference',
      group: 'content',
      to: [{ type: 'category' }],
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      group: 'content',
      of: [{ type: 'string' }],
      options: { layout: 'tags' },
    }),
    defineField({
      name: 'standfirst',
      title: 'Standfirst',
      type: 'text',
      group: 'content',
      description: 'Used as the card excerpt.',
      validation: (r) => r.max(220),
    }),
    defineField({
      name: 'mainImage',
      title: 'Main image',
      type: 'image',
      group: 'content',
      options: { hotspot: true },
      fields: [
        defineField({
          name: 'alt',
          title: 'Alt text',
          type: 'string',
          validation: (r) => r.required(),
        }),
        defineField({ name: 'caption', title: 'Caption', type: 'string' }),
        defineField({ name: 'credit', title: 'Credit', type: 'string' }),
      ],
    }),
    defineField({
      name: 'body',
      title: 'Body',
      type: 'richText',
      group: 'content',
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'myths',
      title: 'Myths',
      type: 'array',
      group: 'content',
      description: 'Shown only when article type is Myth-buster.',
      of: [
        {
          type: 'object',
          name: 'myth',
          fields: [
            defineField({
              name: 'myth',
              title: 'Myth',
              type: 'string',
              validation: (r) => r.required(),
            }),
            defineField({
              name: 'fact',
              title: 'Fact',
              type: 'text',
              validation: (r) => r.required(),
            }),
            defineField({ name: 'sourceUrl', title: 'Source URL', type: 'url' }),
          ],
        },
      ],
      hidden: ({ document }) => document?.articleType !== 'mythBuster',
    }),
    defineField({
      name: 'doctorQuestions',
      title: 'Doctor questions',
      type: 'array',
      group: 'content',
      description: 'Shown only when article type is Doctor guide. Printable checklist.',
      of: [
        {
          type: 'object',
          name: 'doctorQuestion',
          fields: [
            defineField({
              name: 'question',
              title: 'Question',
              type: 'string',
              validation: (r) => r.required(),
            }),
            defineField({ name: 'whyItMatters', title: 'Why it matters', type: 'text' }),
          ],
        },
      ],
      hidden: ({ document }) => document?.articleType !== 'doctorGuide',
    }),
    defineField({
      name: 'author',
      title: 'Author',
      type: 'reference',
      group: 'meta',
      to: [{ type: 'author' }],
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'medicalReviewer',
      title: 'Medical reviewer',
      type: 'reference',
      group: 'meta',
      to: [{ type: 'author' }],
      validation: (r) => r.warning('Recommended for health content'),
    }),
    defineField({
      name: 'publishedAt',
      title: 'Published at',
      type: 'datetime',
      group: 'meta',
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'lastReviewedAt',
      title: 'Last reviewed at',
      type: 'datetime',
      group: 'meta',
      description: 'Shows a "Review due" badge in Studio after 12 months.',
    }),
    defineField({
      name: 'sources',
      title: 'Sources',
      type: 'array',
      group: 'meta',
      of: [
        {
          type: 'object',
          name: 'source',
          fields: [
            defineField({
              name: 'title',
              title: 'Title',
              type: 'string',
              validation: (r) => r.required(),
            }),
            defineField({ name: 'url', title: 'URL', type: 'url' }),
            defineField({ name: 'publisher', title: 'Publisher', type: 'string' }),
            defineField({ name: 'year', title: 'Year', type: 'number' }),
          ],
        },
      ],
    }),
    defineField({
      name: 'relatedArticles',
      title: 'Related articles',
      type: 'array',
      group: 'meta',
      of: [{ type: 'reference', to: [{ type: 'article' }] }],
      validation: (r) => r.max(3),
    }),
    defineField({
      name: 'featured',
      title: 'Featured',
      type: 'boolean',
      group: 'meta',
      initialValue: false,
    }),
    defineField({
      name: 'contentWarning',
      title: 'Content warning',
      type: 'string',
      group: 'meta',
    }),
    defineField({ name: 'seo', title: 'SEO', type: 'seo', group: 'seo' }),
  ],
  preview: {
    select: { title: 'title', type: 'articleType', media: 'mainImage' },
    prepare: ({ title, type, media }) => ({ title, subtitle: type, media }),
  },
})
