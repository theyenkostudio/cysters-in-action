import { defineField, defineType } from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  groups: [
    { name: 'identity', title: 'Identity', default: true },
    { name: 'contact', title: 'Contact & socials' },
    { name: 'legal', title: 'Legal & SEO' },
    { name: 'developer', title: 'Developer' },
  ],
  fields: [
    defineField({
      name: 'siteName',
      title: 'Site name',
      type: 'string',
      group: 'identity',
      initialValue: 'Cysters In Action',
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'tagline',
      title: 'Tagline',
      type: 'string',
      group: 'identity',
      validation: (r) => r.max(120),
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      type: 'image',
      group: 'identity',
      description: 'Full colour. SVG preferred.',
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'logoOnDark',
      title: 'Logo (on dark backgrounds)',
      type: 'image',
      group: 'identity',
      description: 'Reversed/light version, used on inverse-theme sections such as the footer.',
    }),
    defineField({
      name: 'favicon',
      title: 'Favicon',
      type: 'image',
      group: 'identity',
      description: 'Square, 512×512 recommended.',
    }),
    defineField({
      name: 'contactEmail',
      title: 'Contact email',
      type: 'email',
      group: 'contact',
      validation: (r) => r.required(),
    }),
    defineField({ name: 'mediaEmail', title: 'Media email', type: 'email', group: 'contact' }),
    defineField({
      name: 'partnershipsEmail',
      title: 'Partnerships email',
      type: 'email',
      group: 'contact',
    }),
    defineField({
      name: 'phone',
      title: 'Phone',
      type: 'string',
      group: 'contact',
      description: 'E.164 format, e.g. +233501234567',
      validation: (r) => r.regex(/^\+[1-9]\d{6,14}$/, { name: 'E.164 phone number' }),
    }),
    defineField({
      name: 'whatsapp',
      title: 'WhatsApp click-to-chat number',
      type: 'string',
      group: 'contact',
      validation: (r) => r.regex(/^\+[1-9]\d{6,14}$/, { name: 'E.164 phone number' }),
    }),
    defineField({ name: 'address', title: 'Address', type: 'address', group: 'contact' }),
    defineField({
      name: 'socialLinks',
      title: 'Social links',
      type: 'array',
      of: [{ type: 'socialLink' }],
      group: 'contact',
    }),
    defineField({
      name: 'defaultSeo',
      title: 'Default SEO',
      type: 'seo',
      group: 'legal',
      description:
        'Fallback metadata for pages that don’t set their own. Title template: "%s · Cysters In Action".',
    }),
    defineField({
      name: 'medicalDisclaimer',
      title: 'Medical disclaimer',
      type: 'richText',
      group: 'legal',
      description: 'Shown on every Learn page and in the footer. Keep it short.',
    }),
    defineField({
      name: 'emailProvider',
      title: 'Email provider',
      type: 'object',
      group: 'developer',
      description: 'Developer-managed. Switching providers is a deploy, not a Studio edit.',
      fields: [
        defineField({
          name: 'provider',
          title: 'Provider',
          type: 'string',
          options: { list: ['brevo', 'mailchimp', 'none'] },
          initialValue: 'none',
        }),
        defineField({ name: 'listId', title: 'List ID', type: 'string' }),
      ],
    }),
    defineField({
      name: 'analyticsId',
      title: 'Analytics ID',
      type: 'string',
      group: 'developer',
      description: 'Developer-managed.',
    }),
  ],
  preview: {
    prepare: () => ({ title: 'Site settings' }),
  },
})
