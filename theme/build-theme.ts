// theme/build-theme.ts — generates app/theme.generated.css from theme.config.ts.
// Run via `npm run theme:build` (also wired into predev/prebuild). Never hand-edit the output file.
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { converter, clampChroma } from 'culori'
import { themeConfig, SCALE_STEPS, type ScaleStep, type SeedName } from './theme.config'

const toOklchRaw = converter('oklch')
const toRgb = converter('rgb')

function toOklch(hex: string) {
  const color = toOklchRaw(hex)
  if (!color) throw new Error(`Could not parse colour "${hex}"`)
  return color
}

function channelToHex(value: number) {
  const clamped = Math.round(Math.max(0, Math.min(1, value)) * 255)
  return clamped.toString(16).padStart(2, '0').toUpperCase()
}

function oklchToHex(l: number, c: number, h: number) {
  const clamped = clampChroma({ mode: 'oklch', l, c, h }, 'oklch')
  const rgb = toRgb(clamped)
  return `#${channelToHex(rgb.r)}${channelToHex(rgb.g)}${channelToHex(rgb.b)}`
}

export type Scale = Record<ScaleStep, string>
export type Scales = Record<SeedName, Scale> & { neutral: Scale & { 0: string } }

export function buildScales(): Scales {
  const scales = {} as Scales

  for (const [name, seed] of Object.entries(themeConfig.seeds) as [
    SeedName,
    { hex: string; anchor: ScaleStep },
  ][]) {
    const { h = 0, c: seedChroma } = toOklch(seed.hex)
    const anchorCurve = themeConfig.chromaCurve[seed.anchor]
    const scale = {} as Scale
    for (const step of SCALE_STEPS) {
      const chroma = seedChroma * (themeConfig.chromaCurve[step] / anchorCurve)
      scale[step] = oklchToHex(themeConfig.lightness[step], chroma, h)
    }
    scale[seed.anchor] = seed.hex.toUpperCase()
    scales[name] = scale
  }

  const neutralSeed = themeConfig.seeds[themeConfig.neutral.hueFrom]
  const { h: neutralHue = 0 } = toOklch(neutralSeed.hex)
  const neutralChroma = themeConfig.neutral.chroma as Record<string, number>
  const neutralScale = { 0: themeConfig.neutral.canvas.toUpperCase() } as Scale & { 0: string }
  for (const step of SCALE_STEPS) {
    const chroma = neutralChroma[step] ?? neutralChroma.rest
    neutralScale[step] = oklchToHex(themeConfig.lightness[step], chroma, neutralHue)
  }
  scales.neutral = neutralScale

  return scales
}

function resolveToken(value: string): string {
  if (value.startsWith('#')) return value
  const match = /^([a-z]+)-(\d+)$/.exec(value)
  if (!match) throw new Error(`Unrecognised token value "${value}"`)
  return `var(--${match[1]}-${match[2]})`
}

function renderThemeBlock(selector: string, tokens: Record<string, string>) {
  const lines = Object.entries(tokens).map(
    ([key, value]) => `  --color-${key}: ${resolveToken(value)};`,
  )
  return `${selector} {\n${lines.join('\n')}\n}`
}

export function renderCss(scales: Scales): string {
  const scaleLines: string[] = []
  for (const name of Object.keys(themeConfig.seeds) as SeedName[]) {
    for (const step of SCALE_STEPS) scaleLines.push(`  --${name}-${step}: ${scales[name][step]};`)
  }
  scaleLines.push(`  --neutral-0: ${scales.neutral[0]};`)
  for (const step of SCALE_STEPS) scaleLines.push(`  --neutral-${step}: ${scales.neutral[step]};`)

  const statusLines: string[] = []
  for (const [status, { text, bg, solid }] of Object.entries(themeConfig.status)) {
    statusLines.push(`  --status-${status}-text: ${text};`)
    statusLines.push(`  --status-${status}-bg: ${bg};`)
    statusLines.push(`  --status-${status}-solid: ${solid};`)
  }

  const rootTokens = { ...themeConfig.themes.default }
  const rootBlock = renderThemeBlock(':root', rootTokens).replace(
    /^:root \{\n/,
    `:root {\n${scaleLines.join('\n')}\n${statusLines.join('\n')}\n`,
  )

  const inverseBlock = renderThemeBlock("[data-theme='inverse']", themeConfig.themes.inverse)
  const brandBlock = renderThemeBlock("[data-theme='brand']", themeConfig.themes.brand)

  return [
    '/* This file is generated by theme/build-theme.ts. Do not edit by hand. */',
    rootBlock,
    inverseBlock,
    brandBlock,
    '',
  ].join('\n\n')
}

function main() {
  const scales = buildScales()
  const css = renderCss(scales)
  const outPath = resolve(__dirname, '../app/theme.generated.css')
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, css, 'utf8')
  console.log(`theme/build-theme.ts: wrote ${outPath}`)
}

if (require.main === module) main()
